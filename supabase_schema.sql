create or replace function private.log_order_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into public.order_status_log (order_id, from_status, to_status, changed_by)
    values (new.id, case when tg_op = 'UPDATE' then old.status end, new.status, (select auth.uid()));
  end if;
  return null;
end;
$$;
revoke all on function private.log_order_status() from public, anon, authenticated;

create or replace trigger orders_status_log
  after insert or update of status on public.orders
  for each row execute function private.log_order_status();


