-- Dori Yums — Supabase schema
-- Tables · Row Level Security · order/tracking/promo functions · storage
-- buckets · realtime · seed data (12 flavors, gallery, testimonials,
-- settings).
--
-- How to run: Supabase Dashboard → SQL Editor → paste this whole file → Run.
-- Safe to re-run: every statement is idempotent, and seed rows are only
-- inserted when missing (edits made later from the admin are kept).
--
-- Access model
--   • Visitors (anon): read flavors, gallery and settings; place an order,
--     track an order and check a promo code ONLY through the functions
--     below — they can never read or write the orders table directly.
--   • Owner (admin): a signed-in user listed in private.admin_users gets
--     full access. Signing in alone grants nothing.
--   • Prices and totals are always recomputed in the database by
--     place_order(); whatever the browser sends as a price is ignored.
--
-- After creating the owner account (Authentication → Users → Add user),
-- make it an admin once:
--   insert into private.admin_users (user_id)
--   select id from auth.users where email = 'OWNER_EMAIL_HERE'
--   on conflict do nothing;
-- Then disable public sign-ups: Authentication → Sign In / Providers →
-- turn off "Allow new users to sign up".
-- ══════════════════════════════════════════════════════════════════════


