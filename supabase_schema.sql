create or replace function public.place_order(
  p_customer_name         text,
  p_phone                 text,
  p_wilaya                text,
  p_commune               text,
  p_delivery_type         text,
  p_event_date            date,
  p_box_size              integer,
  p_items                 jsonb,
  p_custom_notes          text    default '',
  p_inspiration_image_url text    default null,
  p_promo_code            text    default null,
  p_request_id            uuid    default null
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_order        public.orders;
  v_promo        public.promo_codes;
  v_pricing      jsonb;
  v_ordering     jsonb;
  v_delivery     jsonb;
  v_name         text := btrim(coalesce(p_customer_name, ''));
  v_wilaya       text := btrim(coalesce(p_wilaya, ''));
  v_commune      text := btrim(coalesce(p_commune, ''));
  v_notes        text := btrim(coalesce(p_custom_notes, ''));
  v_image        text := nullif(btrim(coalesce(p_inspiration_image_url, '')), '');
  v_promo_code   text := nullif(upper(btrim(coalesce(p_promo_code, ''))), '');
  v_today        date := (now() at time zone 'Africa/Algiers')::date;
  v_phone        text;
  v_wilaya_code  integer;
  v_base         integer;
  v_min          integer;
  v_max          integer;
  v_box_step     integer;
  v_flavor_step  integer;
  v_min_lead     integer;
  v_tier         integer;
  v_total_qty    integer;
  v_items        jsonb;
  v_found        integer;
  v_all_avail    boolean;
  v_subtotal     integer;
  v_fee          integer;
  v_discount     integer := 0;
begin
  -- the same submission (double tap, retry after a network error) returns the same order
  if p_request_id is not null then
    select * into v_order from public.orders where request_id = p_request_id;
    if found then
      return private.order_receipt(v_order);
    end if;
  end if;

  if coalesce((select (value->>'enabled')::boolean from public.site_settings where key = 'holiday_mode'), false) then
    raise exception 'orders_paused' using errcode = 'P0001';
  end if;

  select value into v_pricing  from public.site_settings where key = 'pricing';
  select value into v_ordering from public.site_settings where key = 'ordering';
  select value into v_delivery from public.site_settings where key = 'delivery';
  v_base        := coalesce((v_pricing->>'base_unit_price')::integer, 120);
  v_min         := coalesce((v_ordering->>'min_pieces')::integer, 20);
  v_max         := coalesce((v_ordering->>'max_pieces')::integer, 1000);
  v_box_step    := coalesce((v_ordering->>'box_step')::integer, 0);
  v_flavor_step := coalesce((v_ordering->>'flavor_step')::integer, 1);
  v_min_lead    := coalesce((v_ordering->>'min_lead_days')::integer, 0);

  -- customer & delivery
  if length(v_name) not between 2 and 80 then
    raise exception 'invalid_name' using errcode = 'P0001';
  end if;
  v_phone := private.normalize_dz_phone(p_phone);
  if v_phone is null then
    raise exception 'invalid_phone' using errcode = 'P0001';
  end if;
  v_wilaya_code := (substring(v_wilaya from '^(\d{1,2})'))::integer;
  if v_wilaya_code is null or v_wilaya_code not between 1 and 58 or length(v_wilaya) > 60 then
    raise exception 'invalid_wilaya' using errcode = 'P0001';
  end if;
  if p_delivery_type is null or p_delivery_type not in ('delivery', 'pickup') then
    raise exception 'invalid_delivery_type' using errcode = 'P0001';
  end if;
  if length(v_commune) > 80 or (p_delivery_type = 'delivery' and length(v_commune) < 2) then
    raise exception 'invalid_commune' using errcode = 'P0001';
  end if;
  if p_event_date is null or p_event_date < v_today + v_min_lead or p_event_date > v_today + 365 then
    raise exception 'invalid_event_date' using errcode = 'P0001';
  end if;
  if length(v_notes) > 1000 then
    raise exception 'invalid_notes' using errcode = 'P0001';
  end if;
  if v_image is not null and v_image !~ '^inspirations/[0-9a-f-]{36}\.(jpg|jpeg|png|webp|heic|heif)$' then
    raise exception 'invalid_image' using errcode = 'P0001';
  end if;

  -- light anti-spam: at most 3 orders per phone number in 10 minutes
  if (select count(*) from public.orders o
       where o.phone = v_phone and o.created_at > now() - interval '10 minutes') >= 3 then
    raise exception 'too_many_orders' using errcode = 'P0001';
  end if;

  -- items: [{flavor_id, qty}], each flavor once, quantities are whole positive numbers
  -- (separate checks: SQL does not guarantee the evaluation order of OR branches)
  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'invalid_items' using errcode = 'P0001';
  end if;
  if jsonb_array_length(p_items) not between 1 and 30
     or exists (
          select 1 from jsonb_array_elements(p_items) e
           where case
                   when jsonb_typeof(e) <> 'object'
                     or coalesce(e->>'flavor_id', '') !~ '^\d{1,18}$'
                     or coalesce(e->>'qty', '') !~ '^\d{1,4}$' then true
                   when (e->>'qty')::integer = 0 then true
                   when v_flavor_step > 1 and (e->>'qty')::integer % v_flavor_step <> 0 then true
                   else false
                 end)
     or (select count(distinct e->>'flavor_id') from jsonb_array_elements(p_items) e) <> jsonb_array_length(p_items)
  then
    raise exception 'invalid_items' using errcode = 'P0001';
  end if;

  select sum((e->>'qty')::integer) into v_total_qty from jsonb_array_elements(p_items) e;
  if p_box_size is null or v_total_qty <> p_box_size
     or v_total_qty not between v_min and v_max
     or (v_box_step > 0 and v_total_qty % v_box_step <> 0) then
    raise exception 'invalid_box_size' using errcode = 'P0001';
  end if;

  -- tiered pricing: the tier with the highest min_qty reached by the whole box
  select coalesce((
    select (t->>'discount_per_piece')::integer
      from jsonb_array_elements(coalesce(v_pricing->'tiers', '[]'::jsonb)) t
     where (t->>'min_qty')::integer <= v_total_qty
     order by (t->>'min_qty')::integer desc
     limit 1), 0)
  into v_tier;

  -- priced snapshot, from the database prices only
  select
    jsonb_agg(jsonb_build_object(
      'flavor_id',  f.id,
      'name_fr',    f.name_fr,
      'name_en',    f.name_en,
      'name_ar',    f.name_ar,
      'qty',        i.qty,
      'unit_price', greatest(coalesce(f.price, v_base) - v_tier, 0),
      'line_total', i.qty * greatest(coalesce(f.price, v_base) - v_tier, 0)
    ) order by f.sort_order, f.id),
    sum(i.qty * greatest(coalesce(f.price, v_base) - v_tier, 0)),
    count(*),
    bool_and(f.is_available)
  into v_items, v_subtotal, v_found, v_all_avail
  from (select (e->>'flavor_id')::bigint as flavor_id, (e->>'qty')::integer as qty
          from jsonb_array_elements(p_items) e) i
  join public.flavors f on f.id = i.flavor_id;

  if v_found <> jsonb_array_length(p_items) then
    raise exception 'invalid_items' using errcode = 'P0001';
  end if;
  if not v_all_avail then
    raise exception 'flavor_unavailable' using errcode = 'P0001';
  end if;

  -- delivery fee: per-wilaya fee, else default fee. A null fee (for a wilaya, or as
  -- default_fee) means "no delivery there" — the customer can still choose pickup.
  if p_delivery_type = 'pickup' then
    v_fee := coalesce((v_delivery->>'pickup_fee')::integer, 0);
  elsif v_delivery->'wilaya_fees' ? v_wilaya_code::text then
    if jsonb_typeof(v_delivery->'wilaya_fees'->v_wilaya_code::text) <> 'number' then
      raise exception 'delivery_unavailable' using errcode = 'P0001';
    end if;
    v_fee := (v_delivery->'wilaya_fees'->>v_wilaya_code::text)::integer;
  elsif jsonb_typeof(v_delivery->'default_fee') = 'number' then
    v_fee := (v_delivery->>'default_fee')::integer;
  else
    raise exception 'delivery_unavailable' using errcode = 'P0001';
  end if;

  -- promo code (applies to the macarons, not to delivery)
  if v_promo_code is not null then
    select * into v_promo from public.promo_codes p
     where p.code = v_promo_code and p.is_active and (p.expires_at is null or p.expires_at > now());
    if not found then
      raise exception 'invalid_promo' using errcode = 'P0001';
    end if;
    v_discount := private.promo_discount(v_promo.discount_type, v_promo.discount_value, v_subtotal);
  end if;

  begin
    insert into public.orders (
      request_id, customer_name, phone, wilaya, commune, delivery_type, event_date, box_size,
      items, custom_notes, inspiration_image_url, promo_code,
      subtotal, delivery_fee, discount_amount, total_price
    ) values (
      p_request_id, v_name, v_phone, v_wilaya, v_commune, p_delivery_type, p_event_date, v_total_qty,
      v_items, v_notes, v_image, v_promo_code,
      v_subtotal, v_fee, v_discount, v_subtotal - v_discount + v_fee
    )
    returning * into v_order;
  exception when unique_violation then
    -- two identical submissions raced: return the one that won
    select * into v_order from public.orders where request_id = p_request_id;
    if not found then
      raise;
    end if;
  end;

  return private.order_receipt(v_order);
end;
$$;
