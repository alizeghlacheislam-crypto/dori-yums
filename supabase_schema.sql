-- Order tracking: needs BOTH the tracking code and the phone used for the order.
-- Accepts 'DY-1042', 'dy1042' or '1042'. Returns null when nothing matches.
create or replace function public.track_order(p_tracking_code text, p_phone text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_order public.orders;
  v_phone text := private.normalize_dz_phone(p_phone);
  v_code  text := 'DY-' || regexp_replace(upper(regexp_replace(coalesce(p_tracking_code, ''), '\s', '', 'g')), '^DY-?', '');
begin
  if v_phone is null or v_code !~ '^DY-\d{1,12}$' then
    return null;
  end if;
  select * into v_order from public.orders o where o.tracking_code = v_code and o.phone = v_phone;
  if not found then
    return null;
  end if;
  return private.order_receipt(v_order) || jsonb_build_object(
    'history', (select coalesce(jsonb_agg(jsonb_build_object('status', l.to_status, 'at', l.changed_at)
                                          order by l.changed_at, l.id), '[]'::jsonb)
                  from public.order_status_log l where l.order_id = v_order.id)
  );
end;
$$;
revoke all on function public.track_order(text, text) from public, anon, authenticated;
grant execute on function public.track_order(text, text) to anon, authenticated;

-- Promo check for the order form. Never lists codes; only answers for the code typed.
create or replace function public.validate_promo(p_code text, p_subtotal integer default 0)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_promo public.promo_codes;
begin
  select * into v_promo from public.promo_codes p
   where p.code = upper(btrim(coalesce(p_code, ''))) and p.is_active
     and (p.expires_at is null or p.expires_at > now());
  if not found then
    return jsonb_build_object('valid', false);
  end if;
  return jsonb_build_object(
    'valid',           true,
    'code',            v_promo.code,
    'discount_type',   v_promo.discount_type,
    'discount_value',  v_promo.discount_value,
    'discount_amount', private.promo_discount(v_promo.discount_type, v_promo.discount_value, greatest(coalesce(p_subtotal, 0), 0))
  );
end;
$$;
revoke all on function public.validate_promo(text, integer) from public, anon, authenticated;
grant execute on function public.validate_promo(text, integer) to anon, authenticated;

