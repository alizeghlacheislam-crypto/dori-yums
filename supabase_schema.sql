-- Orders. Money in whole DZD (integers). items = immutable snapshot of what
-- was ordered at that moment: [{flavor_id, name_fr, name_en, name_ar, qty, unit_price, line_total}].
create sequence if not exists public.order_tracking_seq start with 1001;

create table if not exists public.orders (
  id                    bigint generated always as identity primary key,
  tracking_code         text    not null unique default ('DY-' || nextval('public.order_tracking_seq')),
  request_id            uuid    unique,   -- idempotency key sent by the browser: a double-submit returns the same order
  customer_name         text    not null check (length(btrim(customer_name)) between 2 and 80),
  phone                 text    not null check (phone ~ '^\+213[567][0-9]{8}$'),
  wilaya                text    not null check (length(wilaya) between 1 and 60),
  commune               text    not null default '' check (length(commune) <= 80),
  delivery_type         text    not null check (delivery_type in ('delivery', 'pickup')),
  event_date            date    not null,
  box_size              integer not null check (box_size > 0),
  items                 jsonb   not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) > 0),
  custom_notes          text    not null default '' check (length(custom_notes) <= 1000),
  inspiration_image_url text,   -- storage path, e.g. 'inspirations/<uuid>.jpg' (private bucket)
  promo_code            text,
  subtotal              integer not null check (subtotal >= 0),
  delivery_fee          integer not null default 0 check (delivery_fee >= 0),
  discount_amount       integer not null default 0 check (discount_amount >= 0),
  total_price           integer not null check (total_price >= 0),
  status                text    not null default 'pending'
                        check (status in ('pending', 'confirmed', 'baking', 'completed', 'cancelled')),
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  constraint orders_discount_le_subtotal check (discount_amount <= subtotal),
  constraint orders_total_consistent     check (total_price = subtotal - discount_amount + delivery_fee)
);
alter sequence public.order_tracking_seq owned by public.orders.tracking_code;
create index if not exists orders_status_created_idx on public.orders (status, created_at desc);
create index if not exists orders_open_event_date_idx on public.orders (event_date)
  where status in ('pending', 'confirmed', 'baking');
create index if not exists orders_phone_created_idx on public.orders (phone, created_at desc);

