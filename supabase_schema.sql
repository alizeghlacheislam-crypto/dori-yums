grant execute on function private.is_admin() to authenticated;

create or replace function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- '0551 40 17 04', '+213551401704', '00213 551…' → '+213551401704'; anything else → null.
-- Mobile numbers only (05/06/07): orders are confirmed on WhatsApp.
create or replace function private.normalize_dz_phone(p_phone text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  d text := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
begin
  if d like '00%' then d := substr(d, 3); end if;
  if d like '213%' and length(d) = 12 then d := substr(d, 4); end if;
  if d like '0%' then d := substr(d, 2); end if;
  if d ~ '^[567][0-9]{8}$' then return '+213' || d; end if;
  return null;
end;
$$;

-- Discount in DZD for a promo on a given subtotal (never above the subtotal).
create or replace function private.promo_discount(p_type text, p_value integer, p_subtotal integer)
returns integer
language sql
immutable
set search_path = ''
as $$
  select case
    when p_type = 'percentage' then least(round(p_subtotal * p_value / 100.0)::integer, p_subtotal)
    when p_type = 'fixed'      then least(p_value, p_subtotal)
    else 0
  end;
$$;

revoke all on function private.touch_updated_at()                            from public, anon, authenticated;
revoke all on function private.normalize_dz_phone(text)                      from public, anon, authenticated;
revoke all on function private.promo_discount(text, integer, integer)        from public, anon, authenticated;


